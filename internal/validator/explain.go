// Package validator proves or disproves a recommendation by asking the
// planner what it would do.
//
// The heuristic scorer predicts the planner's decision; this package removes
// the guesswork by creating the index hypothetically with the hypopg
// extension and re-planning the affected queries. Nothing is executed and
// nothing is written to disk: hypothetical indexes live in the session's
// memory and vanish when it ends.
//
// EXPLAIN ANALYZE is never used anywhere in idxa. It would execute the
// statement rather than plan it, which for a read-only advisory tool pointed
// at production would be unacceptable. A test enforces this across the whole
// repository.
package validator

import (
	"context"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
)

// Querier is the small slice of a database connection this package needs,
// which keeps it testable without a live server.
type Querier interface {
	QueryRow(ctx context.Context, sql string, args ...any) Row
	Exec(ctx context.Context, sql string, args ...any) error
}

// Row is a single-row result.
type Row interface {
	Scan(dest ...any) error
}

// Plan is what matters from an EXPLAIN result.
type Plan struct {
	// TotalCost is the planner's estimated total cost of the top node.
	TotalCost float64
	// Indexes lists every index the plan would use, anywhere in the tree.
	Indexes []string
	// NodeTypes lists the scan node types encountered, which is how a
	// sequential scan is distinguished from an index scan.
	NodeTypes []string
	// JSON is the raw plan, kept for display.
	JSON string
}

// UsesIndex reports whether the plan references an index whose name contains
// the given fragment. Hypothetical index names are generated by hypopg and
// look like `<13625>btree_orders_customer_id`, so matching is by substring.
func (p Plan) UsesIndex(fragment string) bool {
	for _, name := range p.Indexes {
		if strings.Contains(name, fragment) {
			return true
		}
	}
	return false
}

// UsesHypotheticalIndex reports whether any hypothetical index was used.
// hypopg prefixes its index names with an object identifier in angle
// brackets, which no real index name contains.
func (p Plan) UsesHypotheticalIndex() bool {
	for _, name := range p.Indexes {
		if strings.HasPrefix(name, "<") {
			return true
		}
	}
	return false
}

// HasSeqScan reports whether the plan still falls back to reading the table.
func (p Plan) HasSeqScan() bool {
	for _, t := range p.NodeTypes {
		if t == "Seq Scan" {
			return true
		}
	}
	return false
}

// Explain plans a statement without executing it.
//
// generic selects EXPLAIN (GENERIC_PLAN), which plans a parameterised
// statement without values. It requires PostgreSQL 16 or newer; on older
// servers the caller must supply a statement with literals, because planning
// a statement containing $1 fails outright.
func Explain(ctx context.Context, q Querier, sql string, generic bool) (Plan, error) {
	prefix := "EXPLAIN (FORMAT JSON) "
	if generic {
		prefix = "EXPLAIN (FORMAT JSON, GENERIC_PLAN) "
	}

	var raw string
	if err := q.QueryRow(ctx, prefix+plannable(sql)).Scan(&raw); err != nil {
		return Plan{}, fmt.Errorf("explain: %w", err)
	}
	return parsePlan(raw)
}

// parsePlan extracts cost and index usage from EXPLAIN's JSON output.
func parsePlan(raw string) (Plan, error) {
	var docs []struct {
		Plan map[string]any `json:"Plan"`
	}
	if err := json.Unmarshal([]byte(raw), &docs); err != nil {
		return Plan{}, fmt.Errorf("parse plan json: %w", err)
	}
	if len(docs) == 0 {
		return Plan{}, fmt.Errorf("parse plan json: empty plan array")
	}

	p := Plan{JSON: raw}
	if cost, ok := docs[0].Plan["Total Cost"].(float64); ok {
		p.TotalCost = cost
	}
	walkPlan(docs[0].Plan, &p)
	return p, nil
}

// walkPlan descends the whole plan tree. Indexes can appear well below the
// top node, inside Append members, subplans, initplans and CTEs, so a
// shallow check would miss them and wrongly report an index as unused.
func walkPlan(node map[string]any, p *Plan) {
	if node == nil {
		return
	}

	if t, ok := node["Node Type"].(string); ok {
		p.NodeTypes = append(p.NodeTypes, t)
	}
	if name, ok := node["Index Name"].(string); ok && name != "" {
		p.Indexes = appendUnique(p.Indexes, name)
	}

	// Every key whose value is a list of child plans.
	for _, key := range []string{"Plans", "Subplans", "InitPlan", "SubPlan", "CTE"} {
		children, ok := node[key].([]any)
		if !ok {
			continue
		}
		for _, child := range children {
			if m, ok := child.(map[string]any); ok {
				walkPlan(m, p)
			}
		}
	}
	// Some node kinds nest a single child plan directly.
	if child, ok := node["Plan"].(map[string]any); ok {
		walkPlan(child, p)
	}
}

func appendUnique(list []string, s string) []string {
	for _, v := range list {
		if v == s {
			return list
		}
	}
	return append(list, s)
}

// RenderPlanText produces a readable summary of a plan for the command line,
// since the raw JSON is unpleasant to read.
func RenderPlanText(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "total cost %.2f", p.TotalCost)
	if len(p.NodeTypes) > 0 {
		fmt.Fprintf(&b, "\n  nodes: %s", strings.Join(p.NodeTypes, " -> "))
	}
	if len(p.Indexes) > 0 {
		fmt.Fprintf(&b, "\n  indexes: %s", strings.Join(p.Indexes, ", "))
	} else {
		b.WriteString("\n  indexes: none")
	}
	return b.String()
}

// typedPlaceholder matches a typed literal whose value pg_stat_statements
// has replaced with a placeholder: interval $2, date $1, timestamp $3.
var typedPlaceholder = regexp.MustCompile(
	`(?i)\b(interval|date|timestamptz|timestamp|timetz|time|numeric|decimal|text|jsonb|json|uuid|boolean|bool|bigint|integer|int|smallint|real|float8|float4|float|bytea|inet|cidr|macaddr|varchar|char|money|xml)\s+(\$\d+)\b`)

// plannable rewrites a normalised statement into one the planner accepts.
//
// pg_stat_statements turns interval '7 days' into interval $2, which reads
// naturally but is not SQL: a typed literal must be followed by a string,
// and a placeholder is not one. The same value written as $2::interval is
// equivalent and plans fine, so that is what the planner is given. Nothing
// else about the statement changes, and the rewritten form is used only for
// EXPLAIN.
func plannable(sql string) string {
	return typedPlaceholder.ReplaceAllString(sql, "$2::$1")
}
